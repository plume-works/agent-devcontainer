"""
The checkout's own environment: its uv environment link, the uv sync, and the pre-commit hooks.

See ADR-0081.
"""

from __future__ import annotations

import os
from pathlib import Path
import shlex
import shutil
import subprocess
import sys

import yaml

from agentdev_runtime import settings as env

PREFIX = 'agentdev-runtime project'
HOOK_TYPES = ('pre-commit', 'pre-push', 'pre-merge-commit', 'post-checkout')
GENERATED_MARKER = 'File generated by pre-commit'


def deploy(settings: env.Settings) -> bool:
    return settings.raw('AGENTDEV_RUNTIME_MODE') == env.DEPLOY


def sync(settings: env.Settings) -> int:
    """Link the checkout's ``.venv`` outside deploy mode, then sync the project into it."""
    workspace = Path(settings.get('DEV_WORKSPACE_FOLDER'))
    venv = workspace / '.venv'
    if not deploy(settings):
        if not venv.is_symlink() and (venv / 'pyvenv.cfg').is_file():
            shutil.rmtree(venv)
        link_venv(settings, workspace)
        prune_venvs(settings, workspace)
    return subprocess.run(
        ['uv', 'sync', '--all-groups', '--all-extras'], cwd=workspace, check=False
    ).returncode


def within(root: Path, target: Path) -> bool:
    return os.path.commonpath([root, target]) == str(root)


def link_venv(settings: env.Settings, path: Path) -> int:
    """Link the checkout's ``.venv`` to its own directory under ``AGENTDEV_VENV_ROOT``."""
    if deploy(settings):
        return 0
    try:
        top = git(path, 'rev-parse', '--show-toplevel')
    except OSError:
        return 0
    root = Path(os.path.abspath(settings.get('AGENTDEV_VENV_ROOT')))
    if top.returncode != 0 or not root.parent.is_dir():
        return 0
    checkout = Path(top.stdout.strip())
    target = root / checkout.name
    venv = checkout / '.venv'
    current = linked(checkout)
    if current is not None:
        if not within(root, current) and current.exists():
            print(f'{PREFIX}: leaving .venv -> {current} (outside {root})', file=sys.stderr)
            return 0
        if not within(root, current):
            # A checkout opened before the home volume links into the removed /uv volume.
            print(f'{PREFIX}: replacing dangling .venv -> {current}', file=sys.stderr)
        if current != target:
            venv.unlink()
    elif venv.exists():
        print(f'{PREFIX}: leaving {venv} (not a link)', file=sys.stderr)
        return 0
    target.mkdir(parents=True, exist_ok=True)
    if not venv.is_symlink():
        venv.symlink_to(target)
    record = root / f'{target.name}.checkout'
    if not record.is_file() or record.read_text() != str(checkout):
        record.write_text(str(checkout))
    return 0


def linked(checkout: Path) -> Path | None:
    """Return where the checkout's ``.venv`` link points, or None when it is no link."""
    venv = checkout / '.venv'
    if not venv.is_symlink():
        return None
    return Path(os.path.normpath(checkout / os.readlink(venv)))


def prune_venvs(settings: env.Settings, workspace: Path) -> None:
    """Remove each environment under the venv root that no checkout of any repository uses."""
    root = Path(os.path.abspath(settings.get('AGENTDEV_VENV_ROOT')))
    listed = git(workspace, 'worktree', 'list', '--porcelain')
    if listed.returncode != 0 or not root.is_dir():
        return
    keep = set()
    for line in listed.stdout.splitlines():
        if line.startswith('worktree '):
            checkout = Path(line.removeprefix('worktree '))
            keep.update({root / checkout.name, linked(checkout)})
    for directory in root.iterdir():
        if not directory.is_dir() or directory.is_symlink() or directory in keep:
            continue
        record = root / f'{directory.name}.checkout'
        if record.is_file() and linked(Path(record.read_text())) == directory:
            continue
        shutil.rmtree(directory)
        record.unlink(missing_ok=True)


def missing_executables(config: Path) -> list[tuple[str, str]]:
    """Return each ``language: system`` hook whose ``entry`` executable is not on PATH."""
    try:
        document = yaml.safe_load(config.read_text()) or {}
    except (OSError, yaml.YAMLError):
        return []
    missing = []
    repos = document.get('repos') if isinstance(document, dict) else None
    for repo in repos or []:
        for hook in (repo or {}).get('hooks') or []:
            if not isinstance(hook, dict) or hook.get('language') != 'system':
                continue
            try:
                words = shlex.split(str(hook.get('entry') or ''))
            except ValueError:
                continue
            if words and shutil.which(words[0]) is None:
                missing.append((str(hook.get('id', '?')), words[0]))
    return missing


def warn_missing(config: Path) -> None:
    for hook, executable in missing_executables(config):
        print(
            f'{PREFIX}: warning: hook {hook} runs {executable}, which is not on PATH; the hook '
            'will fail until it is installed',
            file=sys.stderr,
        )


def git(workspace: Path, *args: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        ['git', *args], cwd=workspace, capture_output=True, text=True, check=False
    )


def hooks(settings: env.Settings) -> int:
    """Register the checkout's pre-commit hooks, then name any system hook that cannot run."""
    workspace = Path(settings.get('DEV_WORKSPACE_FOLDER'))
    if settings.raw('AGENTDEV_SKIP_PRE_COMMIT'):
        print('AGENTDEV_SKIP_PRE_COMMIT is set; skipping pre-commit hook installation.')
        return 0
    config = workspace / '.pre-commit-config.yaml'
    if deploy(settings):
        # Deploy startup fails on any hook problem instead of logging and continuing.
        if shutil.which('pre-commit') is None:
            print('pre-commit is not installed', file=sys.stderr)
            return 1
        hooks_path = git(workspace, 'config', '--get', 'core.hooksPath')
        if hooks_path.returncode == 0:
            print(
                f'core.hooksPath is set to {hooks_path.stdout.strip()}; refusing to replace those '
                "hooks with pre-commit's.",
                file=sys.stderr,
            )
            return 1
        hooks_dir = workspace / git(workspace, 'rev-parse', '--git-path', 'hooks').stdout.strip()
        for hook in HOOK_TYPES:
            path = hooks_dir / hook
            if path.is_file() and GENERATED_MARKER not in path.read_text(errors='replace'):
                print(
                    f"{path} is a custom hook; refusing to replace it with pre-commit's.",
                    file=sys.stderr,
                )
                return 1
        # Hook environments build on first use, never at startup.
        installed = subprocess.run(
            ['pre-commit', 'install', *(f'--hook-type={hook}' for hook in HOOK_TYPES)],
            cwd=workspace,
            check=False,
        )
        if installed.returncode != 0:
            return installed.returncode
        warn_missing(config)
        return 0
    if shutil.which('pre-commit') is None:
        print('pre-commit not found')
    command = ['pre-commit', 'install', '--install-hooks']
    for hook in HOOK_TYPES:
        command += ['--hook-type', hook]
    try:
        installed = subprocess.run(command, cwd=workspace, check=False).returncode
    except OSError:
        installed = 127
    if installed != 0:
        home = Path(os.environ.get('HOME') or Path.home())
        cache = Path(os.environ.get('PRE_COMMIT_HOME') or home / '.cache/pre-commit')
        try:
            text = (cache / 'pre-commit.log').read_text(errors='replace')
        except OSError as error:
            text = f'cat: {error}'
        print(f'pre-commit install failed. log: {text}')
    warn_missing(config)
    return 0


def main(argv: list[str]) -> int:
    settings = env.Settings()
    if argv == ['sync']:
        return sync(settings)
    if argv == ['hooks']:
        return hooks(settings)
    if argv[:1] == ['link-venv'] and len(argv) <= 2:
        return link_venv(settings, Path(argv[1] if len(argv) == 2 else '.'))
    print('usage: agentdev-runtime project sync|hooks|link-venv [PATH]', file=sys.stderr)
    return 2
